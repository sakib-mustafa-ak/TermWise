import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import {PGlite} from '@electric-sql/pglite';
import {publicConfig} from '../scripts/public-config.mjs';
const alice='11111111-1111-4111-8111-111111111111',bob='22222222-2222-4222-8222-222222222222',outsider='33333333-3333-4333-8333-333333333333';
test('Public configuration rejects private keys and incomplete settings',()=>{
  assert.deepEqual(publicConfig({}),{supabaseUrl:'',supabaseKey:''});
  assert.throws(()=>publicConfig({SUPABASE_URL:'https://example.supabase.co'}));
  assert.throws(()=>publicConfig({SUPABASE_URL:'https://example.supabase.co',SUPABASE_PUBLISHABLE_KEY:'sb_secret_example'}));
  assert.equal(publicConfig({SUPABASE_URL:'https://example.supabase.co/',SUPABASE_PUBLISHABLE_KEY:'sb_publishable_example'}).supabaseUrl,'https://example.supabase.co');
});
test('Database enforces account isolation, collaboration permissions and snapshot revocation',async t=>{
  const db=new PGlite();
  await db.exec(`create role anon;create role authenticated;create schema auth;
    create table auth.users(id uuid primary key,email text);
    create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
    create function auth.jwt() returns jsonb language sql stable as $$select jsonb_build_object('email',current_setting('request.jwt.claim.email',true))$$;
    grant usage on schema auth to anon,authenticated; grant execute on all functions in schema auth to anon,authenticated;
    insert into auth.users values('${alice}','alice@example.com'),('${bob}','bob@example.com'),('${outsider}','outsider@example.com');`);
  await db.exec(await fs.readFile(new URL('../supabase/schema.sql',import.meta.url),'utf8'));
  const as=async(id,email)=>{await db.exec('reset role');await db.query("select set_config('request.jwt.claim.sub',$1,false),set_config('request.jwt.claim.email',$2,false)",[id,email]);await db.exec('set role authenticated');};
  const scalar=async(sql,args=[])=>Object.values((await db.query(sql,args)).rows[0])[0];
  const document={version:1,budgets:{Groceries:6000},transactions:[{date:'2026-11-12',description:'PRIVATE NOTE',type:'expense',category:'Groceries',amount:1875}]};
  await as(alice,'alice@example.com');
  assert.equal(await scalar('select public.save_budget($1,0)',[JSON.stringify(document)]),1);
  await assert.rejects(()=>db.query('select public.save_budget($1,0)',[JSON.stringify(document)]),/CLOUD_CONFLICT/);
  const group=await scalar("select public.create_household('Flat 4','Alice')");
  const invite=await scalar('select public.invite_housemate($1,$2)',[group,'bob@example.com']);
  await as(outsider,'outsider@example.com');
  assert.deepEqual((await db.query('select * from public.budget_accounts')).rows,[]);
  assert.deepEqual((await db.query('select * from public.households')).rows,[]);
  await assert.rejects(()=>db.query("select public.accept_household_invite($1,'Intruder')",[invite]),/another email/);
  await as(bob,'bob@example.com');
  await assert.rejects(()=>db.query('insert into public.budget_accounts(owner_id,document) values($1,$2)',[alice,JSON.stringify(document)]),/permission denied/);
  await db.query("select public.accept_household_invite($1,'Bob')",[invite]);
  assert.equal((await db.query('select * from public.households')).rows.length,1);
  assert.deepEqual((await db.query('select * from public.budget_accounts')).rows,[]);
  const shares=JSON.stringify({[alice]:5000,[bob]:5000});
  const bill=await scalar("select public.create_household_bill($1,'Internet',10000,'2026-11-20','equal',$2)",[group,shares]);
  await assert.rejects(()=>db.query("select public.create_household_bill($1,'Bad',10000,'2026-11-20','equal',$2)",[group,JSON.stringify({[outsider]:10000})]),/not a household member/);
  await db.query('select public.settle_household_share($1,true)',[bill]);
  assert.deepEqual((await db.query('select settled_ids from public.household_bills')).rows[0].settled_ids,[bob]);
  await as(alice,'alice@example.com');
  await assert.rejects(()=>db.query('select public.delete_household_bill($1)',[bill]),/retained/);
  await assert.rejects(()=>db.query("select public.create_support_snapshot(array['Groceries'],'2026-11-01','2026-11-30','bob@example.com',7,0)"),/Budget changed/);
  const snapshot=await scalar("select public.create_support_snapshot(array['Groceries'],'2026-11-01','2026-11-30','bob@example.com',7,1)");
  await as(bob,'bob@example.com');
  const received=(await db.query('select * from public.support_snapshots')).rows;
  assert.equal(received.length,1);assert.equal(received[0].summary.totals.Groceries,1875);
  assert.ok(!JSON.stringify(received).includes('PRIVATE NOTE'));
  await as(outsider,'outsider@example.com');assert.deepEqual((await db.query('select * from public.support_snapshots')).rows,[]);
  await as(alice,'alice@example.com');await db.query('select public.revoke_support_snapshot($1)',[snapshot]);
  await as(bob,'bob@example.com');assert.deepEqual((await db.query('select * from public.support_snapshots')).rows,[]);
  await as(alice,'alice@example.com');
  const expired=await scalar("select public.create_support_snapshot(array['Groceries'],'2026-11-01','2026-11-30','bob@example.com',1,1)");
  await db.exec('reset role');await db.query("update public.support_snapshots set expires_at=now()-interval '1 second' where id=$1",[expired]);
  await as(bob,'bob@example.com');assert.deepEqual((await db.query('select * from public.support_snapshots')).rows,[]);
  await db.exec('reset role');await db.exec('set role anon');
  await assert.rejects(()=>db.query('select * from public.budget_accounts'),/permission denied/);
  await assert.rejects(()=>db.query('select * from public.support_snapshots'),/permission denied/);
  await db.close();
});
